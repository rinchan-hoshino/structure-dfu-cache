/**
 * Gate 1: Packaged-JAR real NeoForge 1.21.1 black-box E2E GameTest.
 * Zero bypasses: never imports or invokes any internal class of structure_dfu_cache;
 * interacts solely through vanilla Minecraft / NeoForge public APIs, Brigadier commands,
 * StructureTemplateManager, and the real on-disk cache layout.
 */
@Mod(StructureDfuCacheE2eMod.MOD_ID)
@GameTestHolder(StructureDfuCacheE2eMod.MOD_ID)
@PrefixGameTestTemplate(false)
@EventBusSubscriber(modid = StructureDfuCacheE2eMod.MOD_ID, bus = EventBusSubscriber.Bus.MOD)
public final class StructureDfuCacheE2eMod {
    public static final String MOD_ID = "structure_dfu_cache_e2e";

    @SubscribeEvent
    public static void onRegisterGameTests(RegisterGameTestsEvent event) {
        event.register(StructureDfuCacheE2eMod.class);
    }

    @GameTest(template = "empty", templateNamespace = MOD_ID, batch = "structure_dfu_cache_e2e")
    public static void fullBlackBoxJourneyWithJarInJar(GameTestHelper helper) {
        ServerLevel level = helper.getLevel();
        MinecraftServer server = level.getServer();

        // 1. Verify packaged mod + Jar-in-Jar host + nested Jar-in-Jar mod are all genuinely loaded.
        helper.assertTrue(ModList.get().isLoaded("structure_dfu_cache"), "Packaged structure_dfu_cache JAR must be loaded");
        helper.assertTrue(ModList.get().isLoaded("jij_e2e_host"), "Jar-in-Jar host mod must be loaded");
        helper.assertTrue(ModList.get().isLoaded("jij_e2e_nested"), "Jar-in-Jar nested mod must be loaded");

        Path gameDir = FMLPaths.GAMEDIR.get();
        Path cacheRoot = gameDir.resolve("cache").resolve("structure_dfu_cache");
        Path manifestFile = cacheRoot.resolve("manifest.v2");
        Path legacyOverlay = cacheRoot.resolve("overlay/data/jij_e2e_nested/structure/legacy_keep.nbt");
        Path currentOverlay = cacheRoot.resolve("overlay/data/jij_e2e_nested/structure/current_keep.nbt");

        // 2. Verify manifest.v2 was generated by StructureTemplateManagerMixin during real server boot.
        helper.assertTrue(Files.isRegularFile(manifestFile), "manifest.v2 must exist after server boot: " + manifestFile);
        List<String> manifestLines;
        try {
            manifestLines = Files.readAllLines(manifestFile, StandardCharsets.UTF_8);
        } catch (IOException e) {
            helper.fail("Failed to read manifest.v2: " + e.getMessage());
            return;
        }
        helper.assertTrue(!manifestLines.isEmpty() && manifestLines.get(0).startsWith("#v2\t"), "manifest.v2 must have valid #v2 header");

        boolean foundLegacyC = manifestLines.stream()
            .anyMatch(l -> l.startsWith("jij_e2e_nested:structure/legacy_keep.nbt\t") && l.endsWith("\tC"));
        boolean foundCurrentP = manifestLines.stream()
            .anyMatch(l -> l.startsWith("jij_e2e_nested:structure/current_keep.nbt\t") && l.endsWith("\tP"));
        helper.assertTrue(foundLegacyC, "Old DataVersion structure must be marked C in manifest.v2");
        helper.assertTrue(foundCurrentP, "Current DataVersion structure must be marked P in manifest.v2");

        // 3. Verify old structure was truly DFU-upgraded to current DataVersion in overlay/,
        //    while current-version structure wrote ZERO bytes to overlay/.
        helper.assertTrue(Files.isRegularFile(legacyOverlay), "Legacy structure must be materialized in overlay/");
        helper.assertTrue(!Files.exists(currentOverlay), "Current-version structure must NOT be written to overlay/");

        int expectedDataVersion = SharedConstants.getCurrentVersion().getDataVersion().getVersion();
        try {
            CompoundTag upgraded = NbtIo.readCompressed(legacyOverlay, NbtAccounter.unlimitedHeap());
            int actualDataVersion = NbtUtils.getDataVersion(upgraded, -1);
            helper.assertTrue(
                actualDataVersion == expectedDataVersion,
                "Upgraded overlay NBT DataVersion must equal " + expectedDataVersion + " but was " + actualDataVersion
            );
        } catch (IOException e) {
            helper.fail("Failed to read upgraded overlay NBT: " + e.getMessage());
            return;
        }

        // 4. Verify vanilla StructureTemplateManager loads both structures cleanly through the mounted overlay.
        Optional<StructureTemplate> legacyTemplate = server.getStructureManager()
            .get(ResourceLocation.fromNamespaceAndPath("jij_e2e_nested", "legacy_keep"));
        Optional<StructureTemplate> currentTemplate = server.getStructureManager()
            .get(ResourceLocation.fromNamespaceAndPath("jij_e2e_nested", "current_keep"));
        helper.assertTrue(legacyTemplate.isPresent(), "StructureTemplateManager must load upgraded legacy_keep");
        helper.assertTrue(currentTemplate.isPresent(), "StructureTemplateManager must load passthrough current_keep");

        // 5. Verify warm reload hits manifest.v2 fast-path in < 50ms via StructureTemplateManagerMixin.
        long reloadStart = System.nanoTime();
        server.getStructureManager().onResourceManagerReload(server.getResourceManager());
        long reloadMs = TimeUnit.NANOSECONDS.toMillis(System.nanoTime() - reloadStart);
        helper.assertTrue(reloadMs < 50L, "Warm fast-path reload must complete in < 50ms, took " + reloadMs + "ms");

        // 6. Verify Brigadier commands (/structuredfucache status & clear) and permission level 2 gate.
        CommandDispatcher<CommandSourceStack> dispatcher = server.getCommands().getDispatcher();

        List<Component> nonOpOut = new ArrayList<>();
        CommandSourceStack nonOpSource = createSource(server, level, 0, nonOpOut);
        boolean nonOpBlocked = false;
        try {
            dispatcher.execute("structuredfucache status", nonOpSource);
        } catch (CommandSyntaxException expected) {
            nonOpBlocked = true;
        }
        helper.assertTrue(nonOpBlocked, "Permission level 0 source must be blocked from /structuredfucache status");

        boolean nonOpClearBlocked = false;
        try {
            dispatcher.execute("structuredfucache clear", nonOpSource);
        } catch (CommandSyntaxException expected) {
            nonOpClearBlocked = true;
        }
        helper.assertTrue(nonOpClearBlocked, "Permission level 0 source must be blocked from /structuredfucache clear");

        List<Component> opOut = new ArrayList<>();
        CommandSourceStack opSource = createSource(server, level, 2, opOut);
        try {
            int statusResult = dispatcher.execute("structuredfucache status", opSource);
            helper.assertTrue(statusResult == 1, "/structuredfucache status must return 1 for OP (level 2)");
            helper.assertTrue(!opOut.isEmpty(), "/structuredfucache status must send feedback to OP");

            int clearResult = dispatcher.execute("structuredfucache clear", opSource);
            helper.assertTrue(clearResult == 1, "/structuredfucache clear must return 1 for OP (level 2)");
            helper.assertTrue(!Files.exists(manifestFile), "/structuredfucache clear must delete manifest.v2");
            helper.assertTrue(!Files.exists(legacyOverlay), "/structuredfucache clear must delete overlay files");
        } catch (CommandSyntaxException e) {
            helper.fail("OP command execution failed unexpectedly: " + e.getMessage());
            return;
        }

        helper.succeed();
    }

    private static CommandSourceStack createSource(
        MinecraftServer server,
        ServerLevel level,
        int permissionLevel,
        List<Component> sink
    ) {
        CommandSource capture = new CommandSource() {
            @Override
            public void sendSystemMessage(Component message) {
                sink.add(message);
            }

            @Override
            public boolean acceptsSuccess() {
                return true;
            }

            @Override
            public boolean acceptsFailure() {
                return true;
            }

            @Override
            public boolean shouldInformAdmins() {
                return false;
            }
        };
        return new CommandSourceStack(
            capture,
            Vec3.ZERO,
            Vec2.ZERO,
            level,
            permissionLevel,
            "e2e_tester_" + permissionLevel,
            Component.literal("e2e_tester_" + permissionLevel),
            server,
            null
        );
    }
}
